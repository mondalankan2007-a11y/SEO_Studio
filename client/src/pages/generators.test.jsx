import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import { beforeEach, describe, expect, it, vi } from 'vitest';
import Meta from './Meta.jsx';
import Robots from './Robots.jsx';
import Schema from './Schema.jsx';
import App from '../App.jsx';
import { MemoryRouter } from 'react-router-dom';
import { api } from '../lib/api.js';

vi.mock('../lib/api.js', () => ({ api: { get: vi.fn(), post: vi.fn() }, errorMessage: (e) => e?.message || 'Request failed' }));

describe('SEO generator interactions', () => {
  beforeEach(() => vi.clearAllMocks());

  it('renders the workspace shell, checks API health, and navigates between sections', async () => {
    api.get.mockResolvedValue({ data: { ok: true, audits: 0, averageScore: 0, issues: 0, successfulChecks: 0, websites: 0, recent: [] } });
    render(<MemoryRouter><App /></MemoryRouter>);
    expect(await screen.findByText('API connected')).toBeTruthy();
    fireEvent.click(screen.getByRole('link', { name: /Meta generator/ }));
    expect(await screen.findByText('Metadata that travels with your page.')).toBeTruthy();
  });

  it('generates metadata and displays the package HTML and validation result', async () => {
    api.post.mockResolvedValue({ data: { html: '<title>Search ready page</title>', validation: { valid: true, errors: [], warnings: [] } } });
    render(<Meta />);
    fireEvent.change(screen.getByPlaceholderText('The definitive guide to…'), { target: { value: 'Search ready page' } });
    fireEvent.change(screen.getByPlaceholderText('Summarize what this page is about…'), { target: { value: 'A useful description for this search page.' } });
    fireEvent.click(screen.getByRole('button', { name: /Generate metadata/ }));
    await waitFor(() => expect(api.post).toHaveBeenCalledWith('/meta/generate', expect.objectContaining({ title: 'Search ready page' })));
    expect(await screen.findByText('<title>Search ready page</title>')).toBeTruthy();
    expect(screen.getByText('Valid')).toBeTruthy();
  });

  it('adds a robots user-agent group and renders generated robots text', async () => {
    api.post.mockResolvedValue({ data: { content: 'User-agent: *\nDisallow: /private\n' } });
    render(<Robots />);
    fireEvent.click(screen.getByRole('button', { name: /Add user-agent group/ }));
    expect(screen.getAllByDisplayValue('*')).toHaveLength(2);
    fireEvent.change(screen.getAllByPlaceholderText(/admin/)[0], { target: { value: '/private/' } });
    fireEvent.click(screen.getByRole('button', { name: /Generate robots.txt/ }));
    await waitFor(() => expect(api.post).toHaveBeenCalledWith('/robots/generate', expect.objectContaining({ rules: expect.arrayContaining([expect.objectContaining({ userAgent: ['*'] })]) })));
    expect(await screen.findByText(/Disallow: \/private/)).toBeTruthy();
  });

  it('switches schema types and displays JSON-LD generated by the API', async () => {
    api.post.mockResolvedValue({ data: { json: { '@context': 'https://schema.org', '@type': 'Article', headline: 'An honest article' }, script: '<script type="application/ld+json">{}</script>' } });
    render(<Schema />);
    fireEvent.change(screen.getByDisplayValue('Organization'), { target: { value: 'Article' } });
    fireEvent.change(screen.getByLabelText(/Headline/), { target: { value: 'An honest article' } });
    fireEvent.click(screen.getByRole('button', { name: /Generate JSON-LD/ }));
    await waitFor(() => expect(api.post).toHaveBeenCalledWith('/schema/generate', { type: 'Article', data: expect.objectContaining({ headline: 'An honest article' }) }));
    expect(await screen.findByText(/"@type": "Article"/)).toBeTruthy();
  });
});
